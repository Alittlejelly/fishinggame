/**
 * 测试开关（`TEST`）—— 只灌数据、改节奏，不改任何玩法逻辑。
 *
 *   node 里想跑"测试逻辑"（比如临时验某一屏）时注入一个 `{ ...TEST, on: true }` 即可，
 *   页面里不需要写第二套分支。
 *
 * ⚠️ **正式发布必须是 `on: false`**。tools/simulate.mjs 里有断言专门盯着这一条，
 *    改完忘了关、直接发出去，自测会红。
 *
 * `on: false` 时页面走的是：
 *   · 新玩家 LV1，七张地图按等级逐张解锁（STAR_FIRST / STAR_JITTER 的正式节奏）
 *   · 鱼缸空着，等玩家自己钓（`fillTank` 也只在 on 为 true 时才生效）
 *   · 一局只有一次星标鱼机会（`starRepeat` 同时被 on 短路）
 * 另外：装过测试包的设备里已经写进了 123 级 / 满缸 / 假最高分，
 * 光把开关关掉并不会把那些数据变回来 —— 首次启动时 `purgeTestData()` 会清一次（见 fishing.ux）。
 */

export const TEST = {
  on: false,

  // —— 等级 ——
  // 334000 = Lv123。算法见 level.js：星辰档从 316000 起、每级 7600，
  // (334000-316000)/7600 = 2 → 档内第 3 级 → 8*15+2+1 = 123。
  total: 334000,

  // —— 鱼缸 ——
  fillTank: true, // 7 条星标鱼全部预置进去

  // —— 地图卡片上的"最高分" ——
  // 不灌的话卡片会显示「最高 0 分」，看着像没解锁干净；给一组成阶梯的假数据更像真实账号。
  seedBest: true,

  // —— 星标鱼节奏（单位：帧，60 帧 ≈ 1 秒） ——
  starFirst: 30, // 正式版是 210（约 7 秒），这里 0.5 秒就出
  starJitter: 30,
  starGap: 45, // 拉完一条后隔 0.75 秒再出下一条
  starRepeat: true, // false = 退回"一局只出一次"

  // —— 重置策略 ——
  // false：只在"从没灌过"时写一次，之后正常玩（钓的分、进缸的鱼都会留住）
  // true ：每次启动都拍回去，适合反复验同一屏
  resetOnStart: false
}

/** 灌数据用的一次性标记：存过就不再覆盖，免得把测试中钓到的分打回原样 */
export const TEST_SEED_KEY = 'band_pixel_dev_seed'
